create or replace function public.set_ticket_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  if new.status = 'Closed' and old.status is distinct from 'Closed' and new.closed_at is null then
    new.closed_at = now();
  elsif new.status is distinct from 'Closed' then
    new.closed_at = null;
  end if;
  return new;
end;
$$;

drop trigger if exists set_ticket_updated_at on public.tickets;
create trigger set_ticket_updated_at
before update on public.tickets
for each row execute function public.set_ticket_updated_at();

create or replace function public.sync_ticket_message_metadata()
returns trigger
language plpgsql
as $$
begin
  update public.tickets
  set last_reply_at = new.created_at,
      updated_at = now(),
      status = case
        when new.is_internal then status
        when new.author_type = 'customer' and status = 'Answered' then 'Open'
        when new.author_type = 'staff' and status in ('Open', 'In Progress') then 'Answered'
        else status
      end
  where id = new.ticket_id;

  insert into public.ticket_activity_events(ticket_id, company_id, event_type, title, description, created_by, metadata)
  values (
    new.ticket_id,
    new.company_id,
    case when new.is_internal then 'internal_note_added' else 'reply_added' end,
    case when new.is_internal then 'Internal note added' else 'Reply added' end,
    left(new.body, 240),
    new.author_profile_id,
    jsonb_build_object('message_id', new.id, 'author_type', new.author_type)
  );

  return new;
end;
$$;

drop trigger if exists sync_ticket_message_metadata on public.ticket_messages;
create trigger sync_ticket_message_metadata
after insert on public.ticket_messages
for each row execute function public.sync_ticket_message_metadata();

