insert into public.permissions (company_id, module, role, can_view, can_create, can_edit, can_delete, can_assign)
select c.id, 'tickets', r.role, true, r.can_create, r.can_edit, r.can_delete, r.can_assign
from public.companies c
cross join (
  values
    ('super_admin'::public.app_role, true, true, true, true),
    ('admin'::public.app_role, true, true, true, true),
    ('manager'::public.app_role, true, true, true, true),
    ('sales_agent'::public.app_role, true, true, false, false),
    ('viewer'::public.app_role, false, false, false, false)
) as r(role, can_create, can_edit, can_delete, can_assign)
on conflict do nothing;
