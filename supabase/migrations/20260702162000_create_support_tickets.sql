create table if not exists public.tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity,
  company_id uuid not null references public.companies(id) on delete cascade,
  subject text not null,
  description text,
  status text not null default 'Open' check (status in ('Open', 'In Progress', 'Answered', 'On Hold', 'Closed')),
  priority text not null default 'Medium' check (priority in ('Low', 'Medium', 'High', 'Urgent')),
  department text not null default 'Support',
  service text,
  source text not null default 'manual' check (source in ('manual', 'email', 'whatsapp', 'portal', 'agent')),
  tags text[] not null default '{}',
  client_id uuid references public.clients(id) on delete set null,
  contact_id uuid references public.contacts(id) on delete set null,
  project_id uuid references public.projects(id) on delete set null,
  lead_id uuid references public.leads(id) on delete set null,
  assigned_to uuid references public.profiles(id) on delete set null,
  created_by uuid references public.profiles(id) on delete set null,
  first_response_due_at timestamptz,
  resolution_due_at timestamptz,
  last_reply_at timestamptz,
  closed_at timestamptz,
  metadata jsonb not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, ticket_number)
);

create table if not exists public.ticket_messages (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets(id) on delete cascade,
  company_id uuid not null references public.companies(id) on delete cascade,
  author_type text not null default 'staff' check (author_type in ('staff', 'customer', 'system')),
  author_profile_id uuid references public.profiles(id) on delete set null,
  contact_id uuid references public.contacts(id) on delete set null,
  body text not null,
  is_internal boolean not null default false,
  attachments jsonb not null default '[]',
  created_at timestamptz not null default now()
);

create table if not exists public.ticket_activity_events (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets(id) on delete cascade,
  company_id uuid not null references public.companies(id) on delete cascade,
  event_type text not null,
  title text not null,
  description text,
  metadata jsonb not null default '{}',
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists tickets_company_status_idx on public.tickets(company_id, status);
