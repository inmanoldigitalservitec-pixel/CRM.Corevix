-- Corevix CRM — Sales core sections
-- Estimates, payments, credit notes, subscriptions and expenses.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.estimates (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  number bigint generated by default as identity,
  title text not null default 'New Estimate',
  client_id uuid references public.clients(id) on delete set null,
  project_id uuid references public.projects(id) on delete set null,
  deal_id uuid references public.deals(id) on delete set null,
  subtotal numeric(14,2) not null default 0,
  tax numeric(14,2) not null default 0,
  total numeric(14,2) not null default 0,
  status text not null default 'Draft' check (status in ('Draft','Sent','Accepted','Declined','Expired','Converted')),
  date_issued date not null default current_date,
  expiry_date date,
  notes text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  payment_number bigint generated by default as identity,
  invoice_id uuid references public.invoices(id) on delete set null,
  client_id uuid references public.clients(id) on delete set null,
  amount numeric(14,2) not null default 0,
  payment_date date not null default current_date,
  method text not null default 'Manual',
  status text not null default 'Completed' check (status in ('Pending','Completed','Failed','Refunded')),
  reference text,
  notes text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.credit_notes (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  credit_note_number bigint generated by default as identity,
  invoice_id uuid references public.invoices(id) on delete set null,
  client_id uuid references public.clients(id) on delete set null,
  amount numeric(14,2) not null default 0,
  status text not null default 'Draft' check (status in ('Draft','Issued','Applied','Cancelled')),
  date_issued date not null default current_date,
  reason text,
  notes text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.subscriptions (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  name text not null,
  client_id uuid references public.clients(id) on delete set null,
  product_id uuid references public.products(id) on delete set null,
  amount numeric(14,2) not null default 0,
  billing_cycle text not null default 'Monthly' check (billing_cycle in ('Weekly','Monthly','Quarterly','Yearly')),
  status text not null default 'Active' check (status in ('Trial','Active','Paused','Cancelled','Expired')),
  start_date date not null default current_date,
  next_billing_date date,
  end_date date,
  notes text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.expenses (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  title text not null,
  vendor text,
  category text not null default 'General',
  amount numeric(14,2) not null default 0,
  status text not null default 'Pending' check (status in ('Pending','Approved','Paid','Rejected')),
  expense_date date not null default current_date,
  project_id uuid references public.projects(id) on delete set null,
  client_id uuid references public.clients(id) on delete set null,
  receipt_url text,
  notes text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists estimates_company_id_idx on public.estimates(company_id);
create index if not exists estimates_client_id_idx on public.estimates(client_id);
create index if not exists payments_company_id_idx on public.payments(company_id);
create index if not exists payments_invoice_id_idx on public.payments(invoice_id);
create index if not exists credit_notes_company_id_idx on public.credit_notes(company_id);
create index if not exists subscriptions_company_id_idx on public.subscriptions(company_id);
create index if not exists expenses_company_id_idx on public.expenses(company_id);

