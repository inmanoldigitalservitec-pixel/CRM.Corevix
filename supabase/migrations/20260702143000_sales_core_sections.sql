do $$
declare t text;
begin
  foreach t in array array['estimates','payments','credit_notes','subscriptions','expenses'] loop
    execute format('drop trigger if exists %I_set_updated_at on public.%I', t, t);
    execute format('create trigger %I_set_updated_at before update on public.%I for each row execute function public.set_updated_at()', t, t);
    execute format('drop policy if exists "Company members can view %s" on public.%I', t, t);
    execute format('create policy "Company members can view %s" on public.%I for select using (exists (select 1 from public.profiles p where p.user_id = auth.uid() and p.company_id = %I.company_id and coalesce(p.is_active,true)=true))', t, t, t);
    execute format('drop policy if exists "Company members can insert %s" on public.%I', t, t);
    execute format('create policy "Company members can insert %s" on public.%I for insert with check (exists (select 1 from public.profiles p where p.user_id = auth.uid() and p.company_id = %I.company_id and coalesce(p.is_active,true)=true))', t, t, t);
    execute format('drop policy if exists "Company members can update %s" on public.%I', t, t);
    execute format('create policy "Company members can update %s" on public.%I for update using (exists (select 1 from public.profiles p where p.user_id = auth.uid() and p.company_id = %I.company_id and coalesce(p.is_active,true)=true)) with check (exists (select 1 from public.profiles p where p.user_id = auth.uid() and p.company_id = %I.company_id and coalesce(p.is_active,true)=true))', t, t, t, t);
    execute format('drop policy if exists "Company members can delete %s" on public.%I', t, t);
    execute format('create policy "Company members can delete %s" on public.%I for delete using (exists (select 1 from public.profiles p where p.user_id = auth.uid() and p.company_id = %I.company_id and coalesce(p.is_active,true)=true))', t, t, t);
  end loop;
end $$;

insert into public.permissions (company_id, module, role, can_view, can_create, can_edit, can_delete, can_assign)
select c.id, v.module, v.role::public.app_role, v.can_view, v.can_create, v.can_edit, v.can_delete, false
from public.companies c
cross join (values
  ('estimates','admin',true,true,true,true),('estimates','manager',true,true,true,true),('estimates','sales_agent',true,true,true,false),('estimates','viewer',true,false,false,false),
  ('payments','admin',true,true,true,true),('payments','manager',true,true,true,true),('payments','sales_agent',true,true,true,false),('payments','viewer',true,false,false,false),
  ('credit_notes','admin',true,true,true,true),('credit_notes','manager',true,true,true,true),('credit_notes','sales_agent',true,true,true,false),('credit_notes','viewer',true,false,false,false),
  ('subscriptions','admin',true,true,true,true),('subscriptions','manager',true,true,true,true),('subscriptions','sales_agent',true,true,true,false),('subscriptions','viewer',true,false,false,false),
  ('expenses','admin',true,true,true,true),('expenses','manager',true,true,true,true),('expenses','sales_agent',true,true,true,false),('expenses','viewer',true,false,false,false)
) as v(module, role, can_view, can_create, can_edit, can_delete)
on conflict (company_id, module, role) do nothing;
